/*
 * i18next setup. English is bundled (it's the fallback for every missing
 * key); other languages load on demand, one chunk per file. A language is
 * available as soon as its folder exists in src/locales, so a new language
 * from Weblate needs no code change.
 */
import {
	localizeFields,
	localizeWidget,
	type FieldSchema,
	type Translate,
	type WidgetSchema,
} from "@glaze/schemas";
import i18next from "i18next";
import { initReactI18next, useTranslation } from "react-i18next";
import {
	detectLanguage,
	directionOf,
	localeOf,
	normalizeLanguage,
	RTL_TEST_LANGUAGE,
	readSavedLanguage,
	SOURCE_LANGUAGE,
	saveLanguage,
	type TextDirection,
} from "./lib/languages.ts";
import app from "./locales/en/app.json";
import fields from "./locales/en/fields.json";

/** The namespaces: UI text, and the schema texts (generated by `pnpm schemas`). */
export const NAMESPACES = ["app", "fields"] as const;
type Namespace = (typeof NAMESPACES)[number];

/** The English resources, also the shape every translation follows. */
export const SOURCE_RESOURCES = { app, fields } as const;

declare module "i18next" {
	interface CustomTypeOptions {
		defaultNS: "app";
		resources: typeof SOURCE_RESOURCES;
	}
}

type Loader = () => Promise<unknown>;

// One lazy chunk per translation file; English is already bundled above.
const LOADERS: Readonly<Record<string, Loader>> = import.meta.glob([
	"./locales/*/*.json",
	"!./locales/en/*.json",
]);

/** Language code → its folder in src/locales (Weblate may write `pt_BR`). */
const FOLDERS: ReadonlyMap<string, string> = new Map(
	Object.keys(LOADERS)
		.map((path) => /^\.\/locales\/([^/]+)\/app\.json$/.exec(path)?.[1])
		.filter((folder): folder is string => folder !== undefined)
		.map((folder) => [normalizeLanguage(folder), folder]),
);

function loaderFor(language: string, namespace: Namespace): Loader | null {
	const folder = FOLDERS.get(language);
	return folder === undefined
		? null
		: (LOADERS[`./locales/${folder}/${namespace}.json`] ?? null);
}

/** The languages with an app.json, English first. */
const TRANSLATED: readonly string[] = [
	SOURCE_LANGUAGE,
	...[...FOLDERS.keys()].sort(),
];

/** Every language Glaze can show, including the hidden `rtl-test`. */
export const AVAILABLE_LANGUAGES: readonly string[] = [
	...TRANSLATED,
	RTL_TEST_LANGUAGE,
];

/** The languages the picker offers; `rtl-test` only while developing. */
export const PICKER_LANGUAGES: readonly string[] = import.meta.env.DEV
	? AVAILABLE_LANGUAGES
	: TRANSLATED;

/**
 * The text direction of the active language.
 * @returns `rtl` or `ltr`.
 */
export function currentDirection(): TextDirection {
	return directionOf(i18next.language, (code) => i18next.dir(code));
}

function applyToDocument(language: string): void {
	// Tests run without a DOM.
	if (typeof document === "undefined") return;
	const root = document.documentElement;
	root.lang = localeOf(language);
	root.dir = directionOf(language, (code) => i18next.dir(code));
}

async function loadLanguage(language: string): Promise<void> {
	if (language === SOURCE_LANGUAGE) return;
	for (const namespace of NAMESPACES) {
		if (i18next.hasResourceBundle(language, namespace)) continue;
		if (language === RTL_TEST_LANGUAGE) {
			i18next.addResourceBundle(
				language,
				namespace,
				SOURCE_RESOURCES[namespace],
			);
			continue;
		}
		const load = loaderFor(language, namespace);
		// A language with only app.json so far: fields fall back to English.
		if (load === null) continue;
		const module = await load();
		const bundle =
			typeof module === "object" && module !== null && "default" in module
				? module.default
				: module;
		i18next.addResourceBundle(language, namespace, bundle);
	}
}

/**
 * Starts i18next in the detected language (saved choice, then the browser's
 * languages, then English) and loads that language before the first render.
 * @returns Resolves when the UI can render.
 */
export async function initI18n(): Promise<void> {
	const language = detectLanguage(
		readSavedLanguage(),
		typeof navigator === "undefined"
			? []
			: navigator.languages.length > 0
				? navigator.languages
				: [navigator.language],
		AVAILABLE_LANGUAGES,
	);
	i18next.on("languageChanged", applyToDocument);
	await i18next.use(initReactI18next).init({
		lng: SOURCE_LANGUAGE,
		fallbackLng: SOURCE_LANGUAGE,
		ns: [...NAMESPACES],
		defaultNS: "app",
		resources: { [SOURCE_LANGUAGE]: SOURCE_RESOURCES },
		// React escapes everything it renders.
		interpolation: { escapeValue: false },
		returnNull: false,
		react: { useSuspense: false },
	});
	await changeLanguage(language).catch(() => applyToDocument(SOURCE_LANGUAGE));
}

/**
 * Switches the UI language, loading it first, and remembers the choice.
 * @param language - A code from `AVAILABLE_LANGUAGES`.
 * @returns Resolves once the new language is shown.
 */
export async function changeLanguage(language: string): Promise<void> {
	await loadLanguage(language);
	await i18next.changeLanguage(language);
	saveLanguage(language);
}

/**
 * Looks up a schema text (fields.json) in the active language, then English,
 * then the given fallback. No interpolation: help texts may contain `{{ }}`.
 * @param key - E.g. `widget.weather.fields.location.label`.
 * @param fallback - Shown when neither language has the key.
 * @returns The text.
 */
export const fieldText: Translate = (key, fallback) => {
	for (const language of [i18next.language, SOURCE_LANGUAGE]) {
		const text: unknown = i18next.getResource(language, "fields", key);
		if (typeof text === "string" && text !== "") return text;
	}
	return fallback;
};

const fieldCache = new Map<string, FieldSchema[]>();
const widgetCache = new Map<string, WidgetSchema>();

/**
 * Fields with translated labels and help texts (cached per language).
 * @param fields - Generated fields, e.g. `PAGE_FIELDS`.
 * @param prefix - Their place in fields.json: `base`, `page` or `config`.
 * @returns The translated fields.
 */
export function localizedFields(
	fields: readonly FieldSchema[],
	prefix: "base" | "page" | "config",
): FieldSchema[] {
	const key = `${i18next.language}:${prefix}`;
	const cached = fieldCache.get(key);
	if (cached) return cached;
	const result = localizeFields(fields, prefix, fieldText);
	fieldCache.set(key, result);
	return result;
}

/**
 * A widget schema with translated texts (cached per language).
 * @param schema - From `widgetSchema`.
 * @returns The translated schema.
 */
export function localizedWidget(schema: WidgetSchema): WidgetSchema {
	const key = `${i18next.language}:${schema.type}`;
	const cached = widgetCache.get(key);
	if (cached) return cached;
	const result = localizeWidget(schema, fieldText);
	widgetCache.set(key, result);
	return result;
}

/**
 * The UI direction, re-rendering on change. For direction-aware behaviour;
 * layout itself follows `<html dir>` through logical CSS utilities.
 * @returns `rtl` or `ltr`.
 */
export function useDirection(): TextDirection {
	return useLanguage().direction;
}

/**
 * The active language and its direction, re-rendering on change.
 * @returns The language code, its `Intl` locale and its direction.
 */
export function useLanguage(): {
	readonly language: string;
	readonly locale: string;
	readonly direction: TextDirection;
} {
	const { i18n } = useTranslation();
	return {
		language: i18n.language,
		locale: localeOf(i18n.language),
		direction: directionOf(i18n.language, (code) => i18n.dir(code)),
	};
}

export { i18next as i18n };
