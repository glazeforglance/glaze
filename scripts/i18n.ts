// Checks the translations in apps/web/src/locales.
//
//   pnpm i18n --check      report; exit 1 on errors
//   pnpm i18n --write      also update the status table in TRANSLATING.md
//
// Errors (exit 1): invalid JSON; English keys the code doesn't use; keys the
// code uses that English doesn't have; a translation whose {{placeholders}}
// or <tags> differ from English.
// Warnings only: missing or unused keys in a translation, so a half-done
// Weblate translation never breaks CI.
// A stale status table in TRANSLATING.md is only a note: Weblate's pull
// requests don't regenerate it, and `pnpm release:prepare` does.
// fields.json is generated by `pnpm schemas` (see its own --check); here it
// is only compared per language.
// The checks live in i18n-files.ts / i18n-lib.ts, shared with release.ts.
// Runs on plain Node (built-in type stripping), so only erasable TypeScript here.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	checkTranslations,
	refreshStatusTable,
	TRANSLATING_FILE,
} from "./i18n-files.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

function main(): void {
	const write = process.argv.slice(2).includes("--write");
	const check = checkTranslations(ROOT);
	console.log(check.table);
	console.log("");
	for (const warning of check.warnings) console.warn(`! ${warning}`);
	for (const error of check.errors) console.error(`✗ ${error}`);

	if (write) {
		const refresh = refreshStatusTable(ROOT);
		if (!refresh.ok) {
			for (const error of refresh.errors) console.error(`✗ ${error}`);
			process.exit(1);
		}
		if (refresh.after !== refresh.before) {
			writeFileSync(join(ROOT, TRANSLATING_FILE), refresh.after);
		}
		console.log(`Updated the status table in ${TRANSLATING_FILE}.`);
	} else if (check.staleTable) {
		console.log(
			`· The status table in ${TRANSLATING_FILE} is out of date; \`pnpm release:prepare\` (or \`pnpm i18n --write\`) refreshes it.`,
		);
	}

	if (check.errors.length > 0) process.exit(1);
	const count = check.status.languages.length;
	const warnings = check.warnings.length;
	console.log(
		`✓ Translations OK (${count} language${count === 1 ? "" : "s"} besides English, ${warnings} warning${warnings === 1 ? "" : "s"}).`,
	);
}

main();
