// Generates packages/schemas/src/generated/ from the Glance source: one
// schema per widget type, plus the shared widget, page and config fields.
//
//   pnpm schemas                          download Glance v0.8.7 and write the files
//   pnpm schemas --source ../glance       read a local Glance checkout instead
//   pnpm schemas --tag v0.9.0             another Glance version
//   pnpm schemas --check                  compare with what's committed, exit 1 when stale
//
// Overrides (labels, help, enums, …) come from packages/schemas/overrides.ts.
// Runs on plain Node (built-in type stripping), so only erasable TypeScript here.

import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { OVERRIDES } from "../packages/schemas/overrides.ts";
import {
	buildSchemas,
	type SchemaSet,
	unclassified,
} from "./schema-gen/build.ts";
import { parsePackage } from "./schema-gen/go-parse.ts";
import {
	downloadSource,
	type GlanceSource,
	readLocalSource,
} from "./schema-gen/go-source.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "packages/schemas/src/generated");
const DEFAULT_TAG = "v0.8.7";

const HEADER = (tag: string) =>
	`// Generated by scripts/generate-widget-schemas.ts from Glance ${tag}.\n// Don't edit by hand: change packages/schemas/overrides.ts and run \`pnpm schemas\`.\n`;

function json(value: unknown): string {
	return JSON.stringify(value, null, "\t");
}

/** `hacker-news` → `hackerNews`, so every widget gets a valid identifier. */
function identifier(type: string): string {
	return type.replace(/-([a-z])/g, (_, letter: string) => letter.toUpperCase());
}

/**
 * Renders the generated files.
 * @param set - The schemas.
 * @returns File paths relative to the output folder, and their contents.
 */
export function renderFiles(set: SchemaSet): Map<string, string> {
	const files = new Map<string, string>();
	const head = HEADER(set.generatedFrom);
	for (const widget of set.widgets) {
		files.set(
			`widgets/${widget.type}.ts`,
			`${head}import type { WidgetSchema } from "../../types.ts";\n\n/** The \`${widget.type}\` widget (${widget.goStruct} in the Glance source). */\nexport const schema: WidgetSchema = ${json(widget)};\n`,
		);
	}
	const fields = (name: string, doc: string, value: unknown) =>
		`${head}import type { FieldSchema } from "../types.ts";\n\n/** ${doc} */\nexport const ${name}: readonly FieldSchema[] = ${json(value)};\n`;
	files.set(
		"base.ts",
		fields("BASE_FIELDS", "Options every widget has (`widgetBase`).", set.base),
	);
	files.set("page.ts", fields("PAGE_FIELDS", "Options of a page.", set.page));
	files.set(
		"config.ts",
		fields(
			"CONFIG_FIELDS",
			"The top-level sections of glance.yml.",
			set.config,
		),
	);
	const imports = set.widgets
		.map(
			(widget) =>
				`import { schema as ${identifier(widget.type)} } from "./widgets/${widget.type}.ts";`,
		)
		.join("\n");
	const entries = set.widgets
		.flatMap((widget) =>
			[widget.type, ...widget.aliases].map(
				(name) => `\t"${name}": ${identifier(widget.type)},`,
			),
		)
		.join("\n");
	files.set(
		"index.ts",
		`${head}import type { WidgetSchema } from "../types.ts";\n${imports}\n\nexport { BASE_FIELDS } from "./base.ts";\nexport { CONFIG_FIELDS } from "./config.ts";\nexport { PAGE_FIELDS } from "./page.ts";\n\n/** The Glance version these schemas were generated from. */\nexport const GENERATED_FROM = "${set.generatedFrom}";\n\n/** Widget types in the order of Glance's widget factory (aliases not included). */\nexport const WIDGET_TYPES: readonly string[] = ${json(set.widgets.map((widget) => widget.type))};\n\n/** Every widget type Glance accepts, aliases included (e.g. \`stocks\`). */\nexport const WIDGET_SCHEMAS: Readonly<Record<string, WidgetSchema>> = {\n${entries}\n};\n`,
	);
	return files;
}

function listFiles(dir: string, base = dir): string[] {
	if (!existsSync(dir)) return [];
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const path = join(dir, entry.name);
		return entry.isDirectory()
			? listFiles(path, base)
			: [relative(base, path).replaceAll("\\", "/")];
	});
}

/** Line endings may differ after a checkout on Windows; content may not. */
function sameText(a: string, b: string): boolean {
	return a.replace(/\r\n/g, "\n") === b.replace(/\r\n/g, "\n");
}

async function loadSource(
	args: readonly string[],
): Promise<{ source: GlanceSource; tag: string }> {
	const option = (name: string) => {
		const index = args.indexOf(name);
		return index === -1 ? null : (args[index + 1] ?? null);
	};
	const tag = option("--tag") ?? DEFAULT_TAG;
	const path = option("--source");
	if (path) return { source: readLocalSource(path), tag };
	console.log(`Downloading Glance ${tag}…`);
	return { source: await downloadSource(tag), tag };
}

async function main(): Promise<void> {
	const args = process.argv.slice(2);
	const { source, tag } = await loadSource(args);
	const glance = parsePackage(source.glance);
	const set = buildSchemas(
		{ glance, others: new Map([["sysinfo", parsePackage(source.sysinfo)]]) },
		OVERRIDES,
		tag,
	);
	// Options the Glance code compares with fixed words must be classified in overrides.ts.
	const open = set.widgets.flatMap((widget) =>
		unclassified(widget.fields, widget.type),
	);
	if (open.length > 0) {
		throw new Error(
			`These options are compared with fixed values in the Glance code; describe them in overrides.ts (an enum, or another kind):\n  ${open.join("\n  ")}`,
		);
	}
	const files = renderFiles(set);

	if (args.includes("--check")) {
		const stale = [...files].filter(([path, text]) => {
			const file = join(OUT, path);
			return !existsSync(file) || !sameText(readFileSync(file, "utf8"), text);
		});
		const extra = listFiles(OUT).filter((path) => !files.has(path));
		if (stale.length > 0 || extra.length > 0) {
			for (const [path] of stale) console.error(`✗ out of date: ${path}`);
			for (const path of extra) console.error(`✗ not generated: ${path}`);
			console.error("Run `pnpm schemas` and commit the result.");
			process.exit(1);
		}
		console.log(`All ${files.size} schema files match Glance ${tag}.`);
		return;
	}
	rmSync(OUT, { recursive: true, force: true });
	for (const [path, text] of files) {
		const file = join(OUT, path);
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, text);
	}
	console.log(
		`Wrote ${files.size} files for ${set.widgets.length} widget types (Glance ${tag}).`,
	);
}

main().catch((error: unknown) => {
	console.error(`✗ ${error instanceof Error ? error.message : String(error)}`);
	process.exit(1);
});
